    public static void Apply(
        PixelBuffer buffer,
        IReadOnlyList<PaletteRgb> palette,
        int bitsPerChannel,
        DitherKind kind)
    {
        switch (kind)
        {
            case DitherKind.None:
                MapNearest(buffer, palette, bitsPerChannel);
                break;
            case DitherKind.FloydSteinberg:
                MapErrorDiffusion(buffer, palette, bitsPerChannel, FloydSteinbergKernel);
                break;
            case DitherKind.Atkinson:
                MapErrorDiffusion(buffer, palette, bitsPerChannel, AtkinsonKernel);
                break;
            case DitherKind.Stucki:
                MapErrorDiffusion(buffer, palette, bitsPerChannel, StuckiKernel);
                break;
            case DitherKind.Bayer4x4:
                MapOrdered(buffer, palette, bitsPerChannel, Bayer4, 4);
                break;
            case DitherKind.Bayer8x8:
                MapOrdered(buffer, palette, bitsPerChannel, Bayer8, 8);
                break;
            case DitherKind.BlueNoise:
                MapOrderedBlueNoise(buffer, palette, bitsPerChannel);
                break;
            default:
                MapNearest(buffer, palette, bitsPerChannel);
                break;
        }
    }

    private static readonly (int dx, int dy, float w)[] FloydSteinbergKernel =
    [
        (1, 0, 7f / 16f),
        (-1, 1, 3f / 16f),
        (0, 1, 5f / 16f),
        (1, 1, 1f / 16f)
    ];

